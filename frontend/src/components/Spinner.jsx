import React from 'react';

export default function Spinner({ size = 'md', className = '' }) {
  const sizeClasses = {
    sm: 'w-4 h-4 border-2',
    md: 'w-6 h-6 border-2',
    lg: 'w-10 h-10 border-3',
  };

  return (
    <div className={`flex justify-center items-center ${className}`}>
      <div
        className={`${sizeClasses[size] || sizeClasses.md} border-t-brand-blue border-r-transparent border-b-brand-blue border-l-brand-blue rounded-full animate-spin`}
      />
    </div>
  );
}
